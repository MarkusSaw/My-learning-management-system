CREATE TABLE management_system.timesheet
(
    id         BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    course_id  BIGINT NOT NULL,
    group_id   BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    start_date DATE   NOT NULL,
    end_date   DATE   NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (course_id) REFERENCES management_system.course (id),
    FOREIGN KEY (group_id) REFERENCES management_system."group" (id),
    FOREIGN KEY (teacher_id) REFERENCES management_system.teacher (id)
);
